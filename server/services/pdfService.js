/**
 * server/services/pdfService.js
 * Renders a reading's detailed report as a simply-styled PDF using
 * pdfkit (pure JS, no native/binary dependencies). Returns the
 * PDFDocument itself so the caller can `.pipe(res)` directly.
 */
'use strict';
const PDFDocument = require('pdfkit');

const CATEGORY_LABEL = { tarot: 'Tarot', astrology: 'Astrology', spreads: 'Sacred Layout Spread' };
const GOLD = '#B8434F';
const INK = '#241D14';
const MUTED = '#6B5D46';

function renderReportPdf(reading, category) {
  const doc = new PDFDocument({ size: 'A4', margins: { top: 64, bottom: 64, left: 64, right: 64 } });

  doc.fillColor(GOLD).font('Helvetica-Bold').fontSize(22).text('TaraWing', { continued: false });
  doc.fillColor(MUTED).font('Helvetica').fontSize(11).text('Read the Cosmos. Find Your Path.');
  doc.moveDown(0.5);
  doc.strokeColor(INK).lineWidth(1).moveTo(doc.x, doc.y).lineTo(doc.page.width - doc.page.margins.right, doc.y).stroke();
  doc.moveDown(1);

  doc.fillColor(INK).font('Helvetica-Bold').fontSize(16).text(`Detailed Report — ${CATEGORY_LABEL[category] || category}`);
  doc.font('Helvetica').fontSize(10).fillColor(MUTED)
    .text(`Type: ${reading.type.replace(/_/g, ' ')}`)
    .text(`Generated: ${new Date(reading.updated_at || reading.created_at).toLocaleString()}`);
  if (reading.question) doc.text(`Question: "${reading.question}"`);
  doc.moveDown(1);

  doc.fillColor(INK).font('Helvetica').fontSize(12).text(reading.detailed_report || '', {
    align: 'left', lineGap: 4,
  });

  doc.moveDown(2);
  doc.fillColor(MUTED).fontSize(9).text(
    'This report is generated by a deterministic, rule-based algorithm — not an AI model. ' +
    'For a bespoke AI-written interpretation, see the Deep Insights report option.',
    { align: 'left' }
  );

  doc.end();
  return doc;
}

module.exports = { renderReportPdf };
